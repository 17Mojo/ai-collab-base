"""scripts/check_node_modules_untracked.py 的测试。

门禁脚本本身也要被测——否则它可能一直报「合规」，
而仓库里的 node_modules 早就回来了。测的是**判定逻辑**，
不是「跑一下没报错」。
"""

import importlib.util
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[2] / "scripts" / "check_node_modules_untracked.py"


def _load_module():
    spec = importlib.util.spec_from_file_location("check_node_modules_untracked", _SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


mod = _load_module()


def test_被跟踪的_node_modules_会被挑出来():
    tracked = [
        "chrome-extension/package-lock.json",
        "chrome-extension/node_modules/jsdom/lib/api.js",
        "chrome-extension/node_modules/.package-lock.json",
    ]
    leaked = mod.find_tracked_node_modules(tracked)
    assert len(leaked) == 2
    assert all("node_modules/" in p for p in leaked)


def test_正常仓库挑不出任何_node_modules():
    tracked = [
        "chrome-extension/package-lock.json",
        "chrome-extension/src/platforms/gemini-adapter.js",
        "chrome-extension/tests/run-tests.mjs",
    ]
    assert mod.find_tracked_node_modules(tracked) == []


def test_嵌套目录下的_node_modules_也会被挑出来():
    tracked = ["tests/playwright/node_modules/playwright-core/index.js"]
    assert len(mod.find_tracked_node_modules(tracked)) == 1


def test_名字里带_node_modules_但不是目录的不算():
    # 目录分隔符是关键：`src/node_modules_helper.js` 是正常源码
    tracked = ["chrome-extension/src/node_modules_helper.js"]
    assert mod.find_tracked_node_modules(tracked) == []


def test_锁文件在库里就不报缺失():
    tracked = ["chrome-extension/package-lock.json"]
    assert mod.find_missing_lockfiles(tracked) == []


def test_锁文件不在库里会被报出来():
    tracked = ["chrome-extension/src/platforms/gemini-adapter.js"]
    missing = mod.find_missing_lockfiles(tracked)
    assert missing == list(mod.REQUIRED_LOCKFILES)


def test_本仓当前状态是合规的():
    """真库自查：node_modules 已取消跟踪，锁文件在库。"""
    repo_root = Path(__file__).resolve().parents[2]
    tracked = mod._git_ls_files(repo_root)
    assert mod.find_tracked_node_modules(tracked) == [], "仓库里还有被跟踪的 node_modules"
    assert mod.find_missing_lockfiles(tracked) == [], "锁文件没入库"


@pytest.mark.parametrize(
    "tracked",
    [
        [],
        ["README.md"],
        ["chrome-extension/package-lock.json", "a/b/c.js"],
    ],
)
def test_各种正常输入都挑不出_node_modules(tracked):
    # 这里只断言「没有 node_modules 泄漏」——锁文件在不在是另一条不变量，
    # 由上面两条专门的用例管。
    assert mod.find_tracked_node_modules(tracked) == []


def test_main_在不合规的临时仓库里返回非零(tmp_path, monkeypatch):
    """端到端：造一个「node_modules 被跟踪」的仓库，确认门禁会拦。"""
    import subprocess

    repo = tmp_path / "repo"
    (repo / "chrome-extension" / "node_modules" / "pkg").mkdir(parents=True)
    (repo / "chrome-extension" / "package-lock.json").write_text("{}", encoding="utf-8")
    (repo / "chrome-extension" / "node_modules" / "pkg" / "index.js").write_text("x", encoding="utf-8")

    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "add", "-f", "."], cwd=repo, check=True)

    rc = mod.main(["--repo-root", str(repo)])
    assert rc == 1, "node_modules 被跟踪时门禁必须拦下来"


def test_main_在合规的临时仓库里返回零(tmp_path):
    import subprocess

    repo = tmp_path / "repo"
    (repo / "chrome-extension" / "node_modules" / "pkg").mkdir(parents=True)
    (repo / "chrome-extension" / "package-lock.json").write_text("{}", encoding="utf-8")
    (repo / "chrome-extension" / "node_modules" / "pkg" / "index.js").write_text("x", encoding="utf-8")

    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    # 只 add 锁文件，node_modules 不进库
    subprocess.run(
        ["git", "add", "chrome-extension/package-lock.json"], cwd=repo, check=True
    )

    rc = mod.main(["--repo-root", str(repo)])
    assert rc == 0, "合规仓库不该被拦"
