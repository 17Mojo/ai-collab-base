#!/usr/bin/env python3
"""守护：node_modules 不得进版本库，但锁文件必须在。

## 为什么要有这个门禁

`node_modules` 曾被跟踪（129 个文件、13 万行）。代价是实的：

1. **仓库虚胖**：依赖代码与本仓源码混在同一个历史里，任何一次
   `git clone` 都要下载别人的依赖源码。
2. **密钥扫描器被噪音淹没**：2026-10-24 之前，扫描器报 251 条命中，
   全部来自 node_modules 的压缩产物与源码标识符。真正的泄露被埋在噪音里，
   门禁因此形同虚设（那次的修法之一就是把 251 条降到 0）。
3. **依赖升级变成人肉合并**：依赖更新要同时改「真源码」和「入库的那份拷贝」，
   两份一旦不一致，谁也不知道哪份是对的。

而 CI 本来就自己装依赖（`npm ci`），入库那份拷贝**从来用不上**。

## 两条不变量

- **不变量 A**：任何 `node_modules/` 下的文件都不得被 git 跟踪。
- **不变量 B**：锁文件必须在版本库里。没有锁文件，`npm ci` 无法复现，
  CI 每次装出来的依赖都可能不同——那才是真正的不确定。

B 同样重要：只做 A 不做 B，等于把「依赖版本不确定」这个真问题
用一个「仓库小了」的问题掩盖过去。

用法：
    python3 scripts/check_node_modules_untracked.py [--repo-root .]
退出码：0 = 合规；1 = 违规（并打印具体文件）
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

# 必须被跟踪的锁文件。存在即视为「依赖可复现」。
REQUIRED_LOCKFILES = (
    "chrome-extension/package-lock.json",
)


def _git_ls_files(repo_root: Path) -> list[str]:
    """列出被跟踪的文件。"""
    proc = subprocess.run(
        ["git", "-C", str(repo_root), "ls-files"],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        print(f"[ERROR] git ls-files 失败：{proc.stderr.strip()}", file=sys.stderr)
        raise SystemExit(2)
    return [line for line in proc.stdout.splitlines() if line]


def find_tracked_node_modules(tracked: list[str]) -> list[str]:
    """挑出落在任何 node_modules/ 目录下的被跟踪文件。"""
    return [p for p in tracked if "node_modules/" in p]


def find_missing_lockfiles(tracked: list[str]) -> list[str]:
    """挑出「应该在版本库里却不在」的锁文件。"""
    tracked_set = set(tracked)
    return [p for p in REQUIRED_LOCKFILES if p not in tracked_set]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo-root",
        default=".",
        help="仓库根目录（默认当前目录）",
    )
    args = parser.parse_args(argv)

    repo_root = Path(args.repo_root).resolve()
    tracked = _git_ls_files(repo_root)

    violations: list[str] = []

    leaked = find_tracked_node_modules(tracked)
    if leaked:
        violations.append(
            f"node_modules 里有 {len(leaked)} 个文件被跟踪了：\n"
            + "\n".join(f"  - {p}" for p in leaked[:20])
            + ("\n  …（其余省略）" if len(leaked) > 20 else "")
        )

    missing_locks = find_missing_lockfiles(tracked)
    if missing_locks:
        violations.append(
            "这些锁文件必须入库（否则 `npm ci` 无法复现依赖版本）：\n"
            + "\n".join(f"  - {p}" for p in missing_locks)
        )

    if violations:
        print("[FAIL] 依赖入库状态不合规：", file=sys.stderr)
        for v in violations:
            print(v, file=sys.stderr)
        print(
            "\n修法：git rm -r --cached <node_modules 目录>\n"
            "      并确认 .gitignore 里已列了该目录；锁文件不要删。",
            file=sys.stderr,
        )
        return 1

    print(
        f"[OK] 依赖入库状态合规："
        f"{len(tracked)} 个被跟踪文件中 0 个落在 node_modules 下，"
        f"{len(REQUIRED_LOCKFILES)} 个锁文件均在库。"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
